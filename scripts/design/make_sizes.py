"""Export responsive WebP sizes from the lossless masters.

Usage: python3 -I make_sizes.py <masters_dir> <placements.json> <public_images_dir> <out_ts>

Each layout has a ladder of page widths (CSS px x device pixel ratio). For every
step, each photo is resized to the width it occupies on that page, so the
browser can pick the right file from `srcset`. Writes `<name>-<width>.webp` and
a TypeScript manifest with the placement and the available widths.
"""
import sys, os, json, glob, shutil
from PIL import Image

masters, placements_path, out_dir, out_ts = sys.argv[1:5]
P = json.load(open(placements_path))
PAGE = {'mobile': 326, 'desktop': 603}
# Page widths in device px: small phone 1x .. 3x phone; tablet 1x .. 1440 @2x.
LADDER = {'mobile': [390, 640, 900], 'desktop': [768, 1206, 1600, 2160, 2894]}
QUALITY = lambda page_px: 80 if page_px <= 1206 else 72  # high-DPR files hide more compression

manifest = {}
total = {}
for layout, units in PAGE.items():
    d = os.path.join(out_dir, layout)
    for f in glob.glob(os.path.join(d, '*.webp')):
        if not os.path.basename(f).startswith('tone-'):
            os.remove(f)
    total[layout] = {}
    for name, p in P[layout].items():
        if name.startswith('tone-'):
            shutil.copy(os.path.join(masters, layout, f'{name}.webp'), os.path.join(d, f'{name}.webp'))
            continue
        im = Image.open(os.path.join(masters, layout, f'{name}.png'))
        widths = []
        for page_px in LADDER[layout]:
            w = round(p['w'] * page_px / units)
            h = round(p['h'] * page_px / units)
            if w > im.width:
                w, h = im.width, im.height
            if widths and w <= widths[-1]:
                continue
            out = im if (w, h) == im.size else im.resize((w, h), Image.LANCZOS)
            path = os.path.join(d, f'{name}-{w}.webp')
            out.save(path, quality=QUALITY(page_px), method=6, alpha_quality=100)
            widths.append(w)
            total[layout].setdefault(page_px, 0)
            total[layout][page_px] += os.path.getsize(path)
        manifest.setdefault(name, {'section': p['section']})
        manifest[name]['m' if layout == 'mobile' else 'd'] = dict(x=p['x'], y=p['y'], w=p['w'], h=p['h'], sizes=widths)

lines = [
    '// Generated by scripts/design/make_sizes.py: photo placement per layout in design units',
    '// (mobile page = 326 units wide, desktop page = 603; y is relative to the section top),',
    '// plus the pixel widths exported as /images/<layout>/<name>-<width>.webp.',
    'export type Box = { x: number; y: number; w: number; h: number; sizes: number[] }',
    'export type ArtName = ' + ' | '.join(f"'{n}'" for n in manifest),
    'export const art: Record<ArtName, { section: string; m: Box; d: Box }> = {',
]
for n, v in manifest.items():
    f = lambda b: '{ x: %d, y: %d, w: %d, h: %d, sizes: [%s] }' % (b['x'], b['y'], b['w'], b['h'], ', '.join(map(str, b['sizes'])))
    lines.append(f"  '{n}': {{ section: '{v['section']}', m: {f(v['m'])}, d: {f(v['d'])} }},")
lines.append('}')
open(out_ts, 'w').write('\n'.join(lines) + '\n')
for layout, t in total.items():
    print(layout, {k: f'{v // 1024} KB' for k, v in t.items()})
